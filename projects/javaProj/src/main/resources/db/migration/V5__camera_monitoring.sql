ALTER TABLE integrity_event ADD COLUMN details VARCHAR(256);
CREATE TABLE monitoring_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id VARCHAR(36) NOT NULL UNIQUE,
    lab_id BIGINT NOT NULL REFERENCES lab_session(id),
    student_id BIGINT NOT NULL REFERENCES user_account(id),
    submission_id BIGINT REFERENCES submission(id),
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    person_count INTEGER NOT NULL,
    phone_count INTEGER NOT NULL,
    multiple_people BOOLEAN NOT NULL,
    phone_detected BOOLEAN NOT NULL,
    detections_json VARCHAR(20000) NOT NULL,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_snapshot_lab_student_time ON monitoring_snapshot(lab_id,student_id,captured_at);
