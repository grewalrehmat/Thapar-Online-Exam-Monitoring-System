CREATE TABLE grade_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id BIGINT NOT NULL REFERENCES submission(id),
 graded_by BIGINT NOT NULL REFERENCES user_account(id),
 score INTEGER NOT NULL CHECK(score BETWEEN 0 AND 100),
 feedback VARCHAR(10000),
 graded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_grade_submission_time ON grade_record(submission_id,graded_at);
