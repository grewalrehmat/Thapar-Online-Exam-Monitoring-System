CREATE TABLE lab_session (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES course(id),
 title VARCHAR(140) NOT NULL,
 question VARCHAR(12000) NOT NULL,
 scheduled_date DATE NOT NULL,
 secure_mode BOOLEAN NOT NULL DEFAULT FALSE,
 camera_monitoring BOOLEAN NOT NULL DEFAULT FALSE,
 status VARCHAR(20) NOT NULL CHECK (status IN ('UPCOMING','ACTIVE','CLOSED','ARCHIVED')),
 created_by BIGINT NOT NULL REFERENCES user_account(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_lab_course_status_date ON lab_session(course_id,status,scheduled_date);
CREATE TABLE lab_group_assignment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lab_id BIGINT NOT NULL REFERENCES lab_session(id),
 group_id BIGINT NOT NULL REFERENCES study_group(id),
 assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_lab_group UNIQUE(lab_id,group_id)
);
CREATE INDEX ix_lab_group_group ON lab_group_assignment(group_id,lab_id);
CREATE TABLE submission (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES user_account(id),
 lab_id BIGINT NOT NULL REFERENCES lab_session(id),
 source_code VARCHAR(100000) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('DRAFT','SUBMITTED','GRADED')),
 last_saved_at TIMESTAMP WITH TIME ZONE NOT NULL,
 submitted_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_submission_student_lab UNIQUE(student_id,lab_id)
);
CREATE INDEX ix_submission_lab_status ON submission(lab_id,status);
CREATE TABLE run_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id BIGINT NOT NULL REFERENCES submission(id),
 source_code VARCHAR(100000) NOT NULL,
 standard_input VARCHAR(10000) NOT NULL,
 standard_output VARCHAR(20000) NOT NULL,
 standard_error VARCHAR(20000) NOT NULL,
 exit_code INTEGER,
 timed_out BOOLEAN NOT NULL DEFAULT FALSE,
 duration_ms BIGINT NOT NULL,
 completed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_run_submission_time ON run_record(submission_id,completed_at);
