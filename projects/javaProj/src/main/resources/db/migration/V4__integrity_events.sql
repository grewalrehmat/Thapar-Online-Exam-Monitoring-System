CREATE TABLE integrity_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id BIGINT NOT NULL REFERENCES lab_session(id),
    student_id BIGINT NOT NULL REFERENCES user_account(id),
    submission_id BIGINT REFERENCES submission(id),
    event_type VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(36) NOT NULL,
    flag_number INTEGER,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_integrity_student_lab_key UNIQUE(student_id, lab_id, idempotency_key)
);
CREATE INDEX ix_integrity_lab_student_time ON integrity_event(lab_id, student_id, occurred_at);
CREATE INDEX ix_integrity_student_time ON integrity_event(student_id, occurred_at);
