CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    roll_number VARCHAR(40),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE study_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE student_enrollment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES user_account(id),
    course_id BIGINT NOT NULL REFERENCES course(id),
    group_id BIGINT NOT NULL REFERENCES study_group(id),
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_student_course UNIQUE (student_id, course_id)
);
CREATE INDEX ix_enrollment_student ON student_enrollment(student_id);
CREATE INDEX ix_enrollment_course_group ON student_enrollment(course_id, group_id);
CREATE TABLE teacher_group_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES user_account(id),
    course_id BIGINT NOT NULL REFERENCES course(id),
    group_id BIGINT NOT NULL REFERENCES study_group(id),
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_teacher_course_group UNIQUE (teacher_id, course_id, group_id)
);
CREATE INDEX ix_teacher_assignment_teacher ON teacher_group_assignment(teacher_id);
CREATE INDEX ix_teacher_assignment_course_group ON teacher_group_assignment(course_id, group_id);
